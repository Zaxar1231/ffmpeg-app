String paramLabel(AppLocalizations l, String fxId, String id) {
  if (fxId == 'graphicEq' && id.startsWith('b')) {
    final hz = graphicEqBands[int.parse(id.substring(1))];
    return hz >= 1000 ? '${(hz / 1000).toStringAsFixed(hz % 1000 == 0 ? 0 : 1)}k' : '$hz';
  }
  if (fxId == 'parametricEq') {
    final n = int.parse(id.substring(1)) + 1;
    return switch (id[0]) {
      'f' => l.fxpBandFreq(n),
      'g' => l.fxpBandGain(n),
      _ => l.fxpBandQ(n),
    };
  }
  return switch (id) {
    'gain' => l.fxpGain,
    'peak' => l.fxpPeak,
    'removeDc' => l.fxpRemoveDc,
